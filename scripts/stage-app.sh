#!/bin/bash
#
# Builds the Electron app for packaging (TASK-301) in a scratch copy, build/app-stage:
# never in packages/app/out, which a running `npm run start` uses. electron-vite bakes
# the tray icons' path relative to `out/` (`out/main` -> `../../resources`), so the
# copy keeps the layout the asar gets: out/, resources/, package.json.
# The renderer is minified here (electron.vite.pack.config.ts extends the app's config),
# and packaging/entry.mjs becomes the package's main entry.
#
#   bash scripts/stage-app.sh      (npm run dist:app)

set -euo pipefail

cd "$(dirname "$0")/.."
readonly APP='packages/app'
readonly STAGE='build/app-stage'

[[ -f "${APP}/package.json" && -d "${APP}/node_modules" ]] || {
  printf 'stage-app: error: %s is missing or not installed (npm ci)\n' "${APP}" >&2
  exit 1
}

# Only this fixed, relative scratch directory is ever replaced.
rm -rf -- "${STAGE}"
mkdir -p -- "${STAGE}"
cp -R -- "${APP}/src" "${APP}/resources" "${STAGE}/"
cp -- "${APP}/package.json" "${APP}/electron.vite.config.ts" "${APP}"/tsconfig*.json "${STAGE}/"
ln -s "../../${APP}/node_modules" "${STAGE}/node_modules"

cat >"${STAGE}/electron.vite.pack.config.ts" <<'TS'
// Generated by scripts/stage-app.sh: the app's own config, with the renderer minified for the package.
import base from './electron.vite.config';

export default {
  ...base,
  renderer: { ...base.renderer, build: { ...base.renderer?.build, minify: true } },
};
TS

(cd "${STAGE}" && ./node_modules/.bin/electron-vite build -c electron.vite.pack.config.ts --logLevel warn)

# The packaged entry (electron-builder `extraMetadata.main`): refuses command-line switches, then out/main/index.js.
cp -- packaging/entry.mjs packaging/argv-guard.mjs "${STAGE}/out/"
printf 'stage-app: built %s/out\n' "${STAGE}"
